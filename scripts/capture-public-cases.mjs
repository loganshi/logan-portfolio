/**
 * Captures real public homepages, without login, form submission or private data.
 * Outputs only successfully captured cases to the public gallery manifest.
 * Current-site screenshots do NOT establish the appearance of historical deliveries.
 */
import { chromium } from "playwright";
import { mkdir, writeFile, stat } from "node:fs/promises";

const targets = [
  { slug: "fk-partners", name: "FK Partners", url: "https://fkpartners.com/" },
  { slug: "experiencias-institucionais", name: "Expo Neon", url: "https://www.exponeon.com.br/" },
  { slug: "solucoes-customizadas", name: "Logan Portfolio", url: "https://logan-portfolio-dun.vercel.app/" },
  { slug: "barcelona-academy", name: "Barça Academy", url: "https://barcaacademy.com.br/" },
  { slug: "fadisp", name: "FADISP", url: "https://fadisp.com.br/" },
];
const DATE = new Date().toISOString().slice(0, 10);
const output = "public/projects";
await mkdir(output, { recursive: true });
const manifest = {};

function isBlocked(pageText) {
  return /just a moment|checking your browser|access denied|please enable javascript and cookies/i.test(pageText.slice(0, 900));
}
async function visit(browser, target, viewport, suffix) {
  const page = await browser.newPage({
    viewport, deviceScaleFactor: 1, isMobile: suffix === "mobile", hasTouch: suffix === "mobile",
    locale: "pt-BR", colorScheme: "light", reducedMotion: "reduce",
  });
  try {
    const response = await page.goto(target.url, { waitUntil: "domcontentloaded", timeout: 45000 });
    if (!response || response.status() >= 400) throw new Error("HTTP " + response?.status());
    await page.waitForTimeout(1800);
    const body = await page.locator("body").innerText({ timeout: 8000 }).catch(() => "");
    if (isBlocked(body)) throw new Error("blocked/challenge page");
    if (body.length < 80) throw new Error("page returned insufficient readable content");
    const file = `${output}/${target.slug}-${suffix}.jpg`;
    await page.screenshot({ path: file, type: "jpeg", quality: 82, fullPage: false, animations: "disabled", timeout: 15000 });
    if ((await stat(file)).size < 7000) throw new Error("screenshot suspiciously small");
    console.log("CAPTURED", target.name, suffix, file, response.status(), page.url());
    return { src: "/" + file.replace(/^public\//, ""), finalUrl: page.url() };
  } finally {
    await page.close();
  }
}

const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
try {
  for (const target of targets) {
    try {
      const desktop = await visit(browser, target, { width: 1440, height: 900 }, "desktop");
      let mobile;
      try {
        mobile = await visit(browser, target, { width: 390, height: 844 }, "mobile");
      } catch (error) {
        console.warn("Mobile screenshot unavailable for", target.slug, String(error));
      }
      manifest[target.slug] = {
        desktop: desktop.src,
        ...(mobile ? { mobile: mobile.src } : {}),
        sourceUrl: desktop.finalUrl,
        capturedAt: DATE,
      };
    } catch (error) {
      console.warn("No verified screenshot for", target.slug, String(error));
    }
  }
} finally {
  await browser.close();
}

const tsSource = `// Generated by scripts/capture-public-cases.mjs from public website screenshots.
// Public websites may have changed since the original 2023–2024 implementations.
export type PublicCaseMedia = {
  desktop: string;
  mobile?: string;
  sourceUrl: string;
  capturedAt: string;
};
export const realProjectMedia: Partial<Record<string, PublicCaseMedia>> = ${JSON.stringify(manifest, null, 2)};
`;
await writeFile("src/content/real-project-media.ts", tsSource, "utf8");
console.log("SUCCESSFULLY_CAPTURED", Object.keys(manifest).length, JSON.stringify(Object.keys(manifest)));
if (!Object.keys(manifest).length) {
  console.warn("No verified public screenshots; the portfolio will retain conceptual art.");
}
